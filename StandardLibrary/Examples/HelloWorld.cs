using CRAB.StandardLibrary;

/// <summary>
/// Simple example demonstrating basic console output using CRAB Standard Library
/// </summary>
class Program
{
    static void Main()
    {
        Console.WriteLine("Hello from CRAB Standard Library!");
        Console.WriteLine();
        Console.WriteLine("This is a basic example of console output.");
        Console.Print("You can also print without a newline... ");
        Console.WriteLine("and continue on the same line!");
        Console.WriteLine();
        Console.WaitForKey();
    }
}
